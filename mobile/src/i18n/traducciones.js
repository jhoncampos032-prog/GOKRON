// Reemplaza {llaves} dentro de un texto traducido con valores reales.
// Ejemplo: interpolar('Hola, {nombre}!', { nombre: 'Juan' }) -> 'Hola, Juan!'
export function interpolar(texto, valores) {
  if (!valores) return texto;
  return Object.keys(valores).reduce(
    (acc, clave) => acc.replace(`{${clave}}`, valores[clave]),
    texto
  );
}
